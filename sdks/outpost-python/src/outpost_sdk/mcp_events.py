_MAX_ERROR_BODY_CHARS = 1024
# Bounds the body parsed out of a duck-typed error; real mcp_error bodies are
# a few hundred bytes.
_MAX_DUCK_BODY_CHARS = 64 * 1024

Method = Literal["events/list", "events/subscribe", "events/unsubscribe"]


@dataclass(frozen=True)
class ErrorCodes:
    """JSON-RPC codes for the MCP Events error kinds.

    Outpost fills ``code`` itself in every ``mcp_error`` it returns (its
    ``MCP_ERROR_CODES`` setting). These codes only cover the errors raised
    locally (a missing principal, a topic outside the allowlist, malformed
    params), so pick the profile matching the Outpost setting.
    """

    invalid_params: int
    not_found: int
    forbidden: int
    resource_exhausted: int
    unsupported: int
    callback_endpoint_error: int
    internal_error: int = -32603


ERROR_CODE_PROFILES: Mapping[str, ErrorCodes] = MappingProxyType(
    {
        # The MCP Events design sketch numbering, which ChatGPT follows.
        "sketch": ErrorCodes(-32602, -32011, -32012, -32013, -32014, -32015),
        # The provisional SEP-3415 numbering.
        "sep-3415": ErrorCodes(-32602, -32023, -32024, -32025, -32026, -32027),
    }
)


def _resolve_codes(codes: Union[str, ErrorCodes, None]) -> ErrorCodes:
    if codes is None:
        return ERROR_CODE_PROFILES["sketch"]
    if isinstance(codes, ErrorCodes):
        return codes
    profile = ERROR_CODE_PROFILES.get(codes)
    if profile is None:
        raise ValueError(f"unknown MCP Events error code profile: {codes!r}")
    return profile


class MCPError(Exception):
    """Outpost rejected an MCP call with an ``mcp_error`` (HTTP 422).

    ``code``, ``message`` and ``data`` are the JSON-RPC error to send back.
    """

    def __init__(self, mcp_error: dict[str, Any], status_code: int = 422) -> None:
        super().__init__(mcp_error["message"])
        self.mcp_error = mcp_error
        self.status_code = status_code
        self.kind: str = mcp_error.get("kind", "")
        self.code: int = mcp_error["code"]
        self.message: str = mcp_error["message"]
        self.data: Any = mcp_error.get("data")


class MCPEventsRequestError(Exception):
    """Any other failure of an MCP endpoint call: a non-422 status, a network
    error, a timeout or a malformed response. ``body`` holds at most the first
    KiB of the response, for logs. Never forward it to MCP clients."""

    def __init__(
        self,
        message: str,
        *,
        status_code: Optional[int] = None,
        body: Optional[str] = None,
    ) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.body = body


class JSONRPCError(Exception):
    """A JSON-RPC error raised by the handlers, to send back as is.

    Raise it from ``resolve_tenant``, ``allowed_topics`` or
    ``resolve_principal`` to answer with your own error; any other exception
    from them becomes a generic internal error.
    """

    def __init__(self, code: int, message: str, data: Any = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.data = data


def _field(value: Any, key: str) -> Any:
    return value.get(key) if isinstance(value, Mapping) else getattr(value, key, None)


def _as_mcp_error(value: Any) -> Optional[dict[str, Any]]:
    """Validates an mcp_error object (a mapping, or a model with attributes)."""
    if value is None:
        return None
    code, message, kind = _field(value, "code"), _field(value, "message"), _field(value, "kind")
    if not isinstance(code, int) or isinstance(code, bool) or not isinstance(message, str):
        return None
    out: dict[str, Any] = {"kind": kind if isinstance(kind, str) else "", "code": code, "message": message}
    data = _field(value, "data")
    if data is not None:
        out["data"] = data.model_dump(mode="json", by_alias=True) if isinstance(data, BaseModel) else data
    return out


def mcp_error_from(err: BaseException) -> Optional[dict[str, Any]]:
    """Returns the ``mcp_error`` an exception carries, by duck typing.

    Recognises this module's MCPError, any exception with an ``mcp_error``
    attribute, one whose ``data`` has an ``mcp_error`` (generated SDK error
    classes), and an Outpost HTTP error with status 422 and a JSON ``body``.
    Returns None for anything else, including malformed objects.
    """
    if isinstance(err, MCPError):
        return err.mcp_error
    found = _as_mcp_error(getattr(err, "mcp_error", None))
    if found is None:
        found = _as_mcp_error(getattr(getattr(err, "data", None), "mcp_error", None))
    if found is not None:
        return found
    body = getattr(err, "body", None)
    if getattr(err, "status_code", None) == 422 and isinstance(body, str) and len(body) <= _MAX_DUCK_BODY_CHARS:
        try:
            parsed = json.loads(body)
        except ValueError:
            return None
        if isinstance(parsed, dict):
            return _as_mcp_error(parsed.get("mcp_error"))
    return None


