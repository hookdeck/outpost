"""MCP Events helpers for Outpost.

Hand-written, not generated by Speakeasy: this module is not tracked in
.speakeasy/gen.lock, so it survives SDK regeneration.

An MCP server offers MCP Events by answering ``events/list``,
``events/subscribe`` and ``events/unsubscribe``. Outpost does the work behind
three endpoints; this module proxies the methods to them:

- ``MCPEventsClient``: a raw-JSON client for the three endpoints. Results are
  forwarded verbatim, never re-shaped by a model.
- ``MCPEventsHandlers``: transport-agnostic async handlers taking the
  authenticated principal and the raw MCP params.
- ``register()``: wires the handlers into a server built with the ``mcp``
  package (version 2 or later).
"""

